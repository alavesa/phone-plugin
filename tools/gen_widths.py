#!/usr/bin/env python3
"""Builds the pixel-width table of Minecraft's default font from a vanilla client jar.

usage: gen_widths.py <client.jar> [out.tsv]

The plugin wraps and aligns message text on the server, so it has to know how wide every character is on the
client. This reads assets/minecraft/font/include/default.json + space.json from the jar and applies the client's own
formula for bitmap glyphs:

    advance = (int)(0.5 + width * height / cell_height) + 1      width = last column with a non-transparent pixel + 1

Output: one "HEX_CODEPOINT<TAB>ADVANCE" line per character, sorted. Characters that are not in the table come from
the unifont fallback on the client; the plugin measures those with a fixed estimate (see ui/FontWidths.java).
Re-run this when Mojang changes the default font.
"""
import json
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pnglib import read_png  # noqa: E402


def main():
    jar = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "font", "default_widths.tsv")
    table = {}
    with zipfile.ZipFile(jar) as z:
        space = json.loads(z.read("assets/minecraft/font/include/space.json"))
        for prov in space["providers"]:
            if prov["type"] == "space":
                for ch, adv in prov["advances"].items():
                    table[ord(ch)] = int(adv)
        default = json.loads(z.read("assets/minecraft/font/include/default.json"))
        # later providers only fill characters the earlier ones did not define
        for prov in default["providers"]:
            if prov["type"] != "bitmap":
                continue
            ns, path = prov["file"].split(":")
            w, h, alpha = read_png(z.read("assets/%s/textures/%s" % (ns, path)))
            rows = prov["chars"]
            cell_h = h // len(rows)
            cell_w = w // len(rows[0])
            scale = prov.get("height", 8) / cell_h
            for ry, row in enumerate(rows):
                for cx, ch in enumerate(row):
                    cp = ord(ch)
                    if cp == 0 or cp in table:
                        continue
                    width = 0
                    for x in range(cell_w - 1, -1, -1):
                        if any(alpha[ry * cell_h + y][cx * cell_w + x] != 0 for y in range(cell_h)):
                            width = x + 1
                            break
                    table[cp] = int(0.5 + width * scale) + 1
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("# Advance widths (GUI pixels) of the Minecraft default font, generated by tools/gen_widths.py\n")
        f.write("# from the vanilla client jar. HEX_CODEPOINT<TAB>ADVANCE. Bold adds 1 px per character.\n")
        for cp in sorted(table):
            f.write("%04X\t%d\n" % (cp, table[cp]))
    print("wrote %d widths to %s" % (len(table), os.path.normpath(out)))


if __name__ == "__main__":
    main()
